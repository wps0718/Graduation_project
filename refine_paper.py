# Apply refinements preserving bold formatting
applied_count = 0
for idx, new_text in refinements.items():
    if idx >= len(doc.paragraphs):
        print(f'Warning: paragraph index {idx} out of range')
        continue

    para = doc.paragraphs[idx]

    # Detect if any run was bold
    was_bold = any(run.bold for run in para.runs)

    # Clear all runs
    for run in para.runs:
        run.text = ''

    # Set new text
    if len(para.runs) > 0:
        para.runs[0].text = new_text
        if was_bold:
            para.runs[0].bold = True
    else:
        run = para.add_run(new_text)
        if was_bold:
            run.bold = True

    applied_count += 1

